"""
Single-GPU rectified flow distillation of the SFT-trained upscaler on the pairs generated by
scripts/generate_distill_pairs.py, for one epoch over all of them. The student starts from the SFT
EMA weights and learns the straight path from noise to the teacher's output:
x_t = (1 - t) * teacher_output + t * noise, velocity target noise - teacher_output, conditioned as
the teacher was. Noise levels t are those of the uniform 1 to STUDENT_MAX_STEPS step Euler
schedules; pure noise (t = 1, used by all schedules and alone by the 1 step student) gets
FULL_NOISE_SAMPLE_FRACTION of the samples, the rest is split equally between the 2 to
STUDENT_MAX_STEPS step schedules and over their remaining steps. Sample the student with uniform
sigmas (sigma_shift = 1.0). The LR is linearly decayed to zero over the last
PAIR_TRAINING_DECAY_FRACTION of the steps. A resumed run trains the remaining steps on a reshuffled
pass over the data.

Usage: python scripts/run_pair_distill.py --run-name NAME [--max-steps N]
"""

import argparse
import time
from pathlib import Path

import torch
import torch.nn.functional as functional
from safetensors.torch import load_file
from torch.utils.data import DataLoader
from torch.utils.tensorboard import SummaryWriter

from stdev.distill.config import (
    ADAM_BETAS,
    DATA_WORKERS_PER_RANK,
    FULL_NOISE_SAMPLE_FRACTION,
    GRADIENT_CLIP_NORM,
    KEPT_CHECKPOINTS,
    LOG_INTERVAL_STEPS,
    PAIR_TRAINING_BATCH_SIZE,
    PAIR_TRAINING_CHECKPOINT_INTERVAL_STEPS,
    PAIR_TRAINING_DECAY_FRACTION,
    PAIR_TRAINING_EMA_DECAY,
    PAIR_TRAINING_GRADIENT_CHECKPOINTING,
    PAIR_TRAINING_LEARNING_RATE,
    PAIR_TRAINING_MICRO_BATCH_SIZE,
    PAIR_TRAINING_POOL_SHARDS,
    PAIR_TRAINING_WARMUP_STEPS,
    SEED,
    SFT_PAIRS_DIRECTORY,
    SFT_TEACHER_WEIGHTS_PATH,
    STUDENT_MAX_STEPS,
    DistillPaths,
    run_paths,
)
from stdev.distill.data import EpochPairDataset, list_bucket_pair_shards, shard_pair_count
from stdev.distill.train import export_weights
from stdev.upscalers.pretrain_large import UpscalerUNet

TRAINING_DTYPE = torch.bfloat16
DEVICE = torch.device("cuda")
COMPILE_CACHE_SIZE_LIMIT = 64


def training_timesteps() -> tuple[torch.Tensor, torch.Tensor]:
    """
    returns:
        timesteps: [T], values: (0...1], 1 is pure noise; probabilities: [T], sum 1
    """
    weights = {1.0: FULL_NOISE_SAMPLE_FRACTION}
    schedule_mass = (1.0 - FULL_NOISE_SAMPLE_FRACTION) / (STUDENT_MAX_STEPS - 1)
    for steps in range(2, STUDENT_MAX_STEPS + 1):
        for step in range(1, steps):
            timestep = round(1.0 - step / steps, 6)
            weights[timestep] = weights.get(timestep, 0.0) + schedule_mass / (steps - 1)
    timesteps = sorted(weights, reverse=True)
    return torch.tensor(timesteps), torch.tensor([weights[timestep] for timestep in timesteps])


def learning_rate(step: int, total_steps: int) -> float:
    warmup_factor = min(1.0, (step + 1) / PAIR_TRAINING_WARMUP_STEPS)
    decay_start = total_steps * (1.0 - PAIR_TRAINING_DECAY_FRACTION)
    decay_factor = (
        1.0 if step < decay_start else max(0.0, (total_steps - step) / (total_steps - decay_start))
    )
    return PAIR_TRAINING_LEARNING_RATE * warmup_factor * decay_factor


def latest_checkpoint(checkpoints_directory: Path) -> Path | None:
    checkpoints = sorted(checkpoints_directory.glob("checkpoint_*.pt"))
    return checkpoints[-1] if checkpoints else None


def save_checkpoint(
    checkpoints_directory: Path,
    model: torch.nn.Module,
    optimizer: torch.optim.Optimizer,
    ema_parameters: list[torch.Tensor],
    step: int,
) -> None:
    path = checkpoints_directory / f"checkpoint_{step:09d}.pt"
    temporary_path = path.with_suffix(".tmp")
    torch.save(
        {
            "model": model.state_dict(),
            "ema": [parameter.cpu() for parameter in ema_parameters],
            "optimizer": optimizer.state_dict(),
            "step": step,
        },
        temporary_path,
    )
    temporary_path.replace(path)
    for old_path in sorted(checkpoints_directory.glob("checkpoint_*.pt"))[:-KEPT_CHECKPOINTS]:
        old_path.unlink()
    print(f"run_pair_distill: checkpoint {path.name}", flush=True)


def parse_arguments() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    parser.add_argument("--run-name", required=True)
    parser.add_argument(
        "--pairs-directory",
        type=Path,
        default=SFT_PAIRS_DIRECTORY,
        help="Pairs directory (default: stdev.distill.config.SFT_PAIRS_DIRECTORY).",
    )
    parser.add_argument(
        "--init-weights",
        type=Path,
        default=SFT_TEACHER_WEIGHTS_PATH,
        help="Initial weights (default: stdev.distill.config.SFT_TEACHER_WEIGHTS_PATH).",
    )
    parser.add_argument("--max-steps", type=int, default=0, help="smoke test: stop after N steps")
    return parser.parse_args()


def main() -> None:
    arguments = parse_arguments()
    torch.manual_seed(SEED)
    torch.backends.cudnn.benchmark = True
    torch.backends.cuda.matmul.allow_tf32 = True
    torch.backends.cudnn.allow_tf32 = True
    torch._dynamo.config.cache_size_limit = COMPILE_CACHE_SIZE_LIMIT

    paths: DistillPaths = run_paths(arguments.run_name)
    for directory in (paths.checkpoints, paths.export, paths.tensorboard):
        directory.mkdir(parents=True, exist_ok=True)

    shard_paths = list_bucket_pair_shards(arguments.pairs_directory)
    if not shard_paths:
        raise FileNotFoundError(f"no pair shards in {arguments.pairs_directory}")
    pair_count = sum(shard_pair_count(path) for path in shard_paths)
    total_steps = pair_count // PAIR_TRAINING_BATCH_SIZE
    if arguments.max_steps > 0:
        total_steps = min(total_steps, arguments.max_steps)
    accumulation_steps = PAIR_TRAINING_BATCH_SIZE // PAIR_TRAINING_MICRO_BATCH_SIZE

    model = UpscalerUNet(gradient_checkpointing=PAIR_TRAINING_GRADIENT_CHECKPOINTING)
    model.load_state_dict(load_file(str(arguments.init_weights)))
    model = model.to(DEVICE)
    print(f"run_pair_distill: initialized from {arguments.init_weights}", flush=True)
    optimizer = torch.optim.AdamW(
        model.parameters(),
        lr=PAIR_TRAINING_LEARNING_RATE,
        betas=ADAM_BETAS,
        weight_decay=0.0,
        fused=True,
    )
    ema_parameters = [parameter.detach().float().clone() for parameter in model.parameters()]
    step = 0
    checkpoint_path = latest_checkpoint(paths.checkpoints)
    if checkpoint_path is not None:
        checkpoint = torch.load(checkpoint_path, map_location="cpu", weights_only=False)
        model.load_state_dict(checkpoint["model"])
        optimizer.load_state_dict(checkpoint["optimizer"])
        ema_parameters = [parameter.to(DEVICE) for parameter in checkpoint["ema"]]
        step = checkpoint["step"]
        del checkpoint
        print(f"run_pair_distill: resumed from {checkpoint_path.name} at step {step}", flush=True)
    if step >= total_steps:
        print(f"run_pair_distill: already finished at step {step}", flush=True)
        return

    data_loader = DataLoader(
        EpochPairDataset(
            shard_paths,
            PAIR_TRAINING_MICRO_BATCH_SIZE,
            PAIR_TRAINING_POOL_SHARDS,
            seed=SEED + step,
        ),
        batch_size=None,
        num_workers=DATA_WORKERS_PER_RANK,
        pin_memory=True,
        prefetch_factor=4,
    )
    batches = iter(data_loader)
    compiled_model = torch.compile(model)
    parameters = list(model.parameters())
    summary_writer = SummaryWriter(str(paths.tensorboard / "pair_distill"))

    timesteps, timestep_probabilities = (tensor.to(DEVICE) for tensor in training_timesteps())
    levels = ", ".join(
        f"{level:.3f}: {probability:.3f}"
        for level, probability in zip(timesteps.tolist(), timestep_probabilities.tolist())
    )
    print(
        f"run_pair_distill: {len(shard_paths)} shards, {pair_count} pairs, {total_steps} steps of "
        f"{PAIR_TRAINING_BATCH_SIZE} samples, from step {step}\n"
        f"run_pair_distill: timesteps {levels}",
        flush=True,
    )

    loss_sum = torch.zeros((), device=DEVICE)
    loss_count = 0
    interval_start_step = step
    interval_start_time = time.perf_counter()
    torch.cuda.reset_peak_memory_stats()

    while step < total_steps:
        for parameter_group in optimizer.param_groups:
            parameter_group["lr"] = learning_rate(step, total_steps)
        for _ in range(accumulation_steps):
            batch = {
                name: value.to(DEVICE, non_blocking=True) for name, value in next(batches).items()
            }
            latents_teacher = batch["latents_teacher"]
            noise = batch["noise"]
            sigmas = timesteps[
                torch.multinomial(
                    timestep_probabilities, latents_teacher.shape[0], replacement=True
                )
            ]
            blend = sigmas[:, None, None, None]
            noisy_latents = (1.0 - blend) * latents_teacher + blend * noise
            with torch.autocast("cuda", dtype=TRAINING_DTYPE):
                velocity = compiled_model(
                    noisy_latents,
                    sigmas,
                    batch["latents_low"],
                    batch["text_embedding"],
                    batch["text_mask"],
                    batch["high_frequency_features"],
                    batch["high_frequency_mask"],
                )
            loss = functional.mse_loss(velocity.float(), noise - latents_teacher)
            (loss / accumulation_steps).backward()
            loss_sum += loss.detach()
            loss_count += 1
        torch.nn.utils.clip_grad_norm_(parameters, GRADIENT_CLIP_NORM)
        optimizer.step()
        optimizer.zero_grad(set_to_none=True)

        decay = min(PAIR_TRAINING_EMA_DECAY, (1.0 + step) / (10.0 + step))
        torch._foreach_lerp_(
            ema_parameters, [parameter.detach() for parameter in parameters], 1.0 - decay
        )
        step += 1

        if step % LOG_INTERVAL_STEPS == 0 or step == total_steps:
            elapsed = time.perf_counter() - interval_start_time
            mean_loss = loss_sum.item() / max(loss_count, 1)
            steps_per_second = (step - interval_start_step) / max(elapsed, 1e-6)
            peak_memory_gigabytes = torch.cuda.max_memory_allocated() / 1024**3
            summary_writer.add_scalar("train/loss", mean_loss, step)
            summary_writer.add_scalar("train/learning_rate", optimizer.param_groups[0]["lr"], step)
            summary_writer.add_scalar("train/steps_per_second", steps_per_second, step)
            print(
                f"run_pair_distill: step {step}/{total_steps} loss {mean_loss:.4f} "
                f"lr {optimizer.param_groups[0]['lr']:.2e} {steps_per_second:.2f} steps/s "
                f"peak {peak_memory_gigabytes:.1f} GB",
                flush=True,
            )
            loss_sum.zero_()
            loss_count = 0
            interval_start_time = time.perf_counter()
            interval_start_step = step

        if step % PAIR_TRAINING_CHECKPOINT_INTERVAL_STEPS == 0 or step >= total_steps:
            save_checkpoint(paths.checkpoints, model, optimizer, ema_parameters, step)
            export_weights(paths, model, ema_parameters)

    summary_writer.close()
    print(f"run_pair_distill: finished at step {step}", flush=True)


if __name__ == "__main__":
    main()
